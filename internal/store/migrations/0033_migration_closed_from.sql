-- P33: 닫기 전의 상태를 기억한다.
--
-- 적용된 계획도 닫을 수 있게 하면서 생긴 문제 하나를 막는다.
--
-- 닫힌 계획을 다시 열면 지금까지는 언제나 '초안'으로 갔다(그때 리뷰도 지운다).
-- 진행하지 않기로 접었던 계획에는 그것이 맞다 — 다시 논의를 시작하는 자리다.
-- 그런데 **이미 적용된** 계획을 닫았다가 다시 열 때 초안으로 보내면, 실제로는
-- DB에 들어가 있는 변경이 "아직 실행하지 않은 초안"으로 보이게 된다. 그러면
-- 롤백 버튼도 사라져서, 되돌릴 방법이 화면에서 없어진다.
--
-- 그래서 닫을 때 어디서 닫았는지를 적어 두고, 다시 열 때 그 자리로 돌려보낸다.
-- 빈 값은 "예전에 닫혀서 모른다"는 뜻이고, 그때는 지금까지처럼 초안으로 간다.

ALTER TABLE migrations ADD COLUMN closed_from TEXT NOT NULL DEFAULT '';
