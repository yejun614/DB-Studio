-- P29: 구조 화면을 함께 본다.
--
-- 지금까지 구조 화면의 정리(배치·메모·묶음)는 계정별이었다(0022). 그 결정에는
-- 이유가 있었지만, 실제로 쓰이는 방식은 달랐다: 같은 DB를 보는 사람들이 같은 메모를
-- 보고 싶어 했고, 구조에서 붙인 메모가 ERD 초안으로 이어지지 않아 같은 말을 두 번
-- 적어야 했다.
--
-- 그래서 구조 화면을 **문서 하나**로 승격한다. 커넥션마다 kind='structure' 문서가
-- 하나 있고, 구조 화면은 그것을 연다. 이렇게 하면 ERD 편집기가 쓰던 것이 그대로
-- 붙는다: 실시간 방(erdhub), 커서·참여자, 채팅(erd_chat_messages), 되돌리기,
-- op 압축, 그리고 클러스터에서 리플리카가 소켓을 마스터로 중계하는 경로까지.
-- 새 소켓 경로를 만들었다면 그 중계를 다시 만들어야 했다.
--
-- 초안과 다른 점은 두 가지다.
--   - 스키마 레이어는 읽기 전용이다. 테이블·컬럼은 실제 DB에서 읽어 새로 고치고,
--     사람이 고칠 수 있는 것은 배치·메모·묶음뿐이다(서버가 op 종류로 막는다).
--   - 권한은 문서가 아니라 커넥션을 따른다. 이미 그렇게 동작한다 —
--     resolveERDDocument가 커넥션 등급으로만 판정하기 때문이다.
--
-- 0022가 걱정한 "목록 오염"(초안 아닌 것이 초안 목록과 마이그레이션 후보에 섞이는
-- 것)은 이 kind 로 걸러낸다.
ALTER TABLE erd_documents ADD COLUMN kind TEXT NOT NULL DEFAULT 'draft';

-- 커넥션당 구조 문서는 하나다. 둘이 되면 사람마다 다른 방에 들어가 서로의 메모가
-- 보이지 않는데, 그 사실은 화면에서 알 수 없다.
CREATE UNIQUE INDEX idx_erd_documents_structure
    ON erd_documents (connection_id) WHERE kind = 'structure';
