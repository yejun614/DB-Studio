-- P18: 프로바이더별 허용 모델 목록.
--
-- 지금까지 프로바이더에는 기본 모델 하나(default_model)만 있었다. 그것으로는 두 가지를
-- 할 수 없었다.
--
--  1. **사용자가 모델을 고르는 것.** 같은 키로 빠른 모델과 좋은 모델을 나눠 쓰는 것이
--     보통인데, 대화마다 고를 수 없으면 프로바이더를 여러 개 등록해 흉내내야 했다.
--  2. **관리자가 고를 수 있는 범위를 정하는 것.** 키를 등록하는 사람과 쓰는 사람이 다르고,
--     모델마다 비용이 열 배씩 차이 난다. "이 키로는 이 모델들만"이 필요하다.
--
-- JSON 배열로 담는 이유: 이 목록은 통째로 읽고 통째로 쓴다. 개별 모델을 검색하거나
-- 조인할 일이 없고, 별도 표로 빼면 프로바이더 저장이 트랜잭션 두 벌이 된다.
--
-- 빈 배열은 "제한 없음"이다. 이미 돌고 있는 설치에서 목록이 비어 있다고 어시스턴트가
-- 멈추면 안 된다 — 제한은 관리자가 명시적으로 고른 결과여야 한다.
ALTER TABLE ai_providers ADD COLUMN allowed_models TEXT NOT NULL DEFAULT '[]';
