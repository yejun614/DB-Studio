export async function renderManual(outlet) {
  const nav = h('nav.manual-toc', {},
    h('div.manual-toc-head', {}, icon('list', 14), h('strong', {}, '차례')),
    ...SECTIONS.map((s) => h('a.manual-toc-link', { href: `#${s.id}` }, s.title)),
  );

  const article = h('article.manual-body', {},
    h('header.manual-head', {},
      h('h1', {}, 'DB Studio 사용 설명서'),
      h('p.muted', {}, '이 서버에 들어 있는 문서입니다. 화면과 다르면 화면이 맞습니다.'),
    ),
    ...SECTIONS.map((s) => h('section.manual-section', { id: s.id },
      h('h2.manual-section-title', {}, s.title),
      // 설명서의 코드에도 색을 입힌다. 여기 실린 것은 그대로 복사해 쓰는 예제라,
      // 문자열과 키워드가 구분되지 않으면 어디까지가 값인지 눈으로 세어야 한다.
      renderMarkdown(s.body, { highlight: (code, lang) => highlightFragment(code, lang) }),
      s.dynamic ? h('div', { dataset: { dynamic: s.dynamic } }) : null,
    )),
  );

  mount(outlet, h('div.manual-shell', {}, nav, article));
  addCopyButtons(article);
  await fillNodeTable(article);
  // 주소에 #조각이 있으면 그것이 먼저 처리되어 아직 없는 요소를 찾는다.
  // 그리기가 끝난 지금 다시 한 번 맞춘다.
  if (location.hash) {
    document.getElementById(location.hash.slice(1))?.scrollIntoView();
  }
  return () => {};
}

// addCopyButtons는 코드 블록마다 복사 버튼을 붙인다.
//
// 마크다운 렌더러가 아니라 여기서 붙이는 이유: 복사 버튼은 문법이 아니라 이 화면의
// 장치다. 렌더러가 버튼을 만들기 시작하면 그것을 쓰는 다른 화면(어시스턴트 답변,
// ERD 대화)까지 원하지 않는 버튼을 얻게 된다.
//
// 코드는 그대로 복사해 쓰라고 실어 둔 것이므로, 손으로 끌어 고르는 단계를 없앤다.
function addCopyButtons(root) {
  for (const pre of root.querySelectorAll('pre.md-code')) {
    const wrap = h('div.md-code-wrap');
    pre.replaceWith(wrap);
    wrap.append(pre, h('button.icon-btn.md-code-copy', {
      type: 'button', title: '코드 복사', 'aria-label': '코드 복사',
      // textContent는 강조용 span을 걷어낸 원문 그대로다.
      onclick: () => copyToClipboard(pre.textContent),
    }, icon('copy', 14)));
  }
}

// fillNodeTable은 노드 목록을 서버에서 받아 채운다.
//
// 문서에 손으로 적지 않는 이유: 노드는 늘어나고, 손으로 적은 목록은 늘어난 다음에
// 틀린 목록이 된다. 권한이 없어 못 받으면 그 사실만 알린다.
async function fillNodeTable(article) {
  const slot = article.querySelector('[data-dynamic="nodes"]');
  if (!slot) return;
  let specs;
  try {
    const meta = await api.get('/macros/meta');
    specs = meta.specs ?? [];
  } catch {
    mount(slot, h('p.muted', {}, '노드 목록은 매크로 사용 권한이 있어야 볼 수 있습니다.'));
    return;
  }

  const groups = new Map();
  for (const spec of specs) {
    const key = spec.group || 'etc';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(spec);
  }
  const GROUP_LABEL = {
    flow: '흐름', db: '데이터베이스', studio: 'DB Studio 기능', script: '스크립트',
  };

  mount(slot, ...[...groups].map(([key, list]) => h('div.manual-nodes', {},
    h('h3.md-h', {}, GROUP_LABEL[key] ?? key),
    h('div.md-table-wrap', {}, h('table.md-table', {},
      h('thead', {}, h('tr', {},
        h('th', {}, '노드'), h('th', {}, '하는 일'), h('th', {}, '포트'))),
      h('tbody', {}, ...list.map((spec) => h('tr', {},
        h('td', {}, h('strong', {}, spec.label), h('div.muted.small', {}, spec.type)),
        h('td', {}, spec.description ?? ''),
        h('td', {}, (spec.ports ?? []).join(', ')),
      ))),
    )),
  )));
}
